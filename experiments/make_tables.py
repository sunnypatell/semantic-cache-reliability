"""Generate the paper's LaTeX result tables from the experiment CSVs.

Numbers are emitted into dcolumn decimal-aligned columns (siunitx is too slow with the
newtx math fonts in this toolchain). The best value in each column is bolded via the
standard \\multicolumn trick. Every number traces to results/reliability_summary.csv,
results/calibration_summary.csv, or the per-cell JSON reports.

Run after run_reliability.py / run_crossencoder.py / run_calibration.py:
    python experiments/make_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "paper" / "tables"
RELI = ROOT / "results" / "reliability"

# Bi-encoders (indexable caches), then the lexical control, then the cross-encoder verifier.
BIENCODERS = ["all-MiniLM-L6-v2", "all-mpnet-base-v2", "e5-small-v2", "e5-large-v2",
              "bge-base-en-v1.5", "bge-large-en-v1.5"]
CONTROLS = ["tfidf-lexical", "cross-encoder-stsb"]
ENC_ORDER = BIENCODERS + CONTROLS
ENC_LABEL = {"all-MiniLM-L6-v2": "MiniLM-L6", "all-mpnet-base-v2": "MPNet-base",
             "e5-small-v2": "E5-small", "e5-large-v2": "E5-large",
             "bge-base-en-v1.5": "BGE-base", "bge-large-en-v1.5": "BGE-large",
             "tfidf-lexical": "TF-IDF (lexical)", "cross-encoder-stsb": "Cross-encoder"}
DOMAINS = ["qqp", "mrpc", "paws"]
DOMAIN_LABEL = {"qqp": "Questions", "mrpc": "News", "paws": "Adversarial"}
DOMAIN_SHORT = {"qqp": "Ques.", "mrpc": "News", "paws": "Adv."}
BASE_RATE = {"qqp": 0.36, "mrpc": 0.68, "paws": 0.44}


def _cell(v: float, best: bool) -> str:
    """A dcolumn-safe cell; bold (centered via multicolumn) when it is the column best."""
    if v != v:  # NaN
        return r"\multicolumn{1}{c}{--}"
    return rf"\multicolumn{{1}}{{c}}{{\bfseries {v:.2f}}}" if best else f"{v:.2f}"


def separability_table(df: pd.DataFrame) -> None:
    encs = [e for e in ENC_ORDER if e in set(df["encoder"])]
    # Column best (max) over all rows, per (metric, domain).
    def col_max(metric: str, dom: str) -> float:
        vals = [df[(df.encoder == e) & (df.dataset == dom)][metric].iloc[0]
                for e in encs if len(df[(df.encoder == e) & (df.dataset == dom)])]
        return max(vals) if vals else float("nan")
    maxes = {(m, d): col_max(m, d) for m in ("pr_auc", "roc_auc") for d in DOMAINS}

    def row(enc: str) -> str:
        cells = [ENC_LABEL[enc] + (r"\tnote{a}" if enc == "cross-encoder-stsb" else "")]
        for m in ("pr_auc", "roc_auc"):
            for d in DOMAINS:
                r = df[(df.encoder == enc) & (df.dataset == d)]
                v = r[m].iloc[0] if len(r) else float("nan")
                cells.append(_cell(v, abs(v - maxes[(m, d)]) < 5e-3))
        return " & ".join(cells) + r" \\"

    bi = "\n      ".join(row(e) for e in encs if e in BIENCODERS)
    ctrl = "\n      ".join(row(e) for e in encs if e in CONTROLS)
    head = (r"\multicolumn{1}{c}{" + DOMAIN_SHORT[d] + "}" for d in DOMAINS)
    head = list(head)
    tex = r"""% Auto-generated by experiments/make_tables.py -- do not edit by hand.
\begin{table}[t]
  \centering
  \begin{threeparttable}
    \caption{Threshold-free separability for every method and domain (point estimates; bold
      is the column best). Higher is better. The neural bi-encoders cluster near the
      adversarial base rate of $0.44$; the lexical control and even a joint cross-encoder do
      not rescue that column, and the lexical control is the single best method on it.}
    \label{tab:separability}
    \small
    \begin{tabular}{l d{2} d{2} d{2} d{2} d{2} d{2}}
      \toprule
      & \multicolumn{3}{c}{\prauc{} $\uparrow$} & \multicolumn{3}{c}{\rocauc{} $\uparrow$} \\
      \cmidrule(lr){2-4}\cmidrule(lr){5-7}
      \multicolumn{1}{l}{Encoder} & """ + " & ".join(head) + " & " + " & ".join(head) + r""" \\
      \midrule
      """ + bi + r"""
      \midrule
      """ + ctrl + r"""
      \bottomrule
    \end{tabular}
    \begin{tablenotes}[flush]\footnotesize
      \item Domains: Questions (\textsc{qqp}, base rate $0.36$), News (\textsc{mrpc}, $0.68$),
            Adversarial (\textsc{paws}, $0.44$). $95\%$ \textsc{bca} bootstrap half-widths are
            $\le 0.04$ throughout; full intervals and operating points are in
            \cref{tab:fullresults}.
      \item[a] A joint cross-encoder verifier, not a drop-in cache: it scores each pair on the
            fly and cannot be \textsc{ann}-indexed. Shown for reference.
    \end{tablenotes}
  \end{threeparttable}
\end{table}
"""
    (TABLES / "separability_table.tex").write_text(tex, encoding="utf-8")
    print("[table] separability_table.tex (PR+ROC, bold winners, cross-encoder)")


def _load_full(enc: str, dom: str) -> dict | None:
    p = RELI / f"{dom}__{enc}.json"
    if not p.exists():
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def fullresults_table(df: pd.DataFrame) -> None:
    """The complete results matrix: every metric we computed, with CIs, grouped by domain."""
    encs = [e for e in ENC_ORDER if e in set(df["encoder"])]

    def ci(d: dict) -> str:
        return f"{d['estimate']:.2f}\\,({d['low']:.2f},{d['high']:.2f})"

    def pct(d: dict) -> str:
        return f"{100*d['estimate']:.1f}"

    blocks = []
    for dom in DOMAINS:
        rows = []
        for enc in encs:
            j = _load_full(enc, dom)
            if j is None:
                continue
            par = j["precision_at_recall"]
            cov = j["coverage_at_max_fhr"]
            rows.append(
                f"{ENC_LABEL[enc]} & {ci(j['pr_auc'])} & {ci(j['roc_auc'])} & "
                f"{par['0.70']['estimate']:.2f} & {par['0.80']['estimate']:.2f} & "
                f"{par['0.90']['estimate']:.2f} & {pct(cov['0.01'])} & {pct(cov['0.05'])} " + r"\\"
            )
        label = f"{DOMAIN_LABEL[dom]} (base rate {BASE_RATE[dom]:.2f})"
        blocks.append(
            r"\multicolumn{8}{l}{\textit{" + label + r"}}\\[1pt]" + "\n      "
            + "\n      ".join(rows)
        )
    body = ("\n      \\addlinespace[3pt]\n      ").join(blocks)
    tex = r"""% Auto-generated by experiments/make_tables.py -- do not edit by hand.
\begin{table*}[t]
  \centering
  \begin{threeparttable}
    \caption{Complete reliability matrix for every method and domain: threshold-free
      separability (\prauc{}, \rocauc{}) with $95\%$ \textsc{bca} bootstrap intervals, the
      precision attainable at three recall targets, and the coverage attainable under two
      false-hit ceilings. This is the full record behind \cref{tab:separability,fig:coverage}.}
    \label{tab:fullresults}
    \footnotesize
    \begin{tabular}{l c c c c c r r}
      \toprule
      & \prauc{} & \rocauc{} & \multicolumn{3}{c}{precision @ recall} & \multicolumn{2}{c}{coverage @ \fhr{} (\%)} \\
      \cmidrule(lr){4-6}\cmidrule(lr){7-8}
      Method & (95\% CI) & (95\% CI) & $0.7$ & $0.8$ & $0.9$ & $\le 1\%$ & $\le 5\%$ \\
      \midrule
      """ + body + r"""
      \bottomrule
    \end{tabular}
    \begin{tablenotes}[flush]\footnotesize
      \item Precision at a recall target is the cleanliness a cache can hold while still
            reusing that share of genuinely reusable answers; coverage at a false-hit ceiling
            is the share of traffic served while keeping errors under the ceiling. The
            cross-encoder is a verifier (not \textsc{ann}-indexable), shown for reference.
    \end{tablenotes}
  \end{threeparttable}
\end{table*}
"""
    (TABLES / "fullresults_table.tex").write_text(tex, encoding="utf-8")
    print("[table] fullresults_table.tex (complete matrix, 24 cells)")


def calibration_table() -> None:
    path = ROOT / "results" / "calibration_summary.csv"
    if not path.exists():
        print("[table] calibration_summary.csv missing; leaving placeholder")
        return
    df = pd.read_csv(path)
    df = df[df.c_fh == 20.0]

    def kind(p: str) -> str:
        if p.startswith("fixed"):
            return r"Fixed ($\thr=0.80$)"
        if p.startswith("fhr"):
            return r"Ceiling (\fhr{} $\le 5\%$)"
        return r"Cost-aware (\cref{alg:calib})"

    df = df.assign(kind=df.policy.map(kind))
    order = [r"Fixed ($\thr=0.80$)", r"Ceiling (\fhr{} $\le 5\%$)", r"Cost-aware (\cref{alg:calib})"]
    agg = {k: df[df.kind == k] for k in order}
    best_cost = min(g.expected_cost.mean() for g in agg.values())
    rows = []
    for k in order:
        g = agg[k]
        c = g.expected_cost.mean()
        cstr = (rf"\multicolumn{{1}}{{c}}{{\bfseries {c:.3f}}}"
                if abs(c - best_cost) < 5e-4 else f"{c:.3f}")
        rows.append(f"{k} & {100*g.fhr.mean():.1f} & {100*g.coverage.mean():.1f} & {cstr} " + r"\\")
    body = "\n      ".join(rows)
    tex = r"""% Auto-generated by experiments/make_tables.py -- do not edit by hand.
\begin{table}[t]
  \centering
  \begin{threeparttable}
    \caption{Threshold policies on held-out test data, averaged over encoders and domains at a
      false-hit penalty of $\cfh=20$. Expected cost is in model calls per query against the
      always-recompute baseline of $1$; lower is better (bold). A fixed default is several
      times more expensive than not caching at all; the principled policies recover the
      baseline, and the cost-aware form reaches it without a hand-set error target.}
    \label{tab:calibration}
    \begin{tabular}{l r r d{3}}
      \toprule
      Policy & \multicolumn{1}{c}{\fhr{} (\%)} & \multicolumn{1}{c}{Coverage (\%)} & \multicolumn{1}{c}{Expected cost $\downarrow$} \\
      \midrule
      """ + body + r"""
      \bottomrule
    \end{tabular}
    \begin{tablenotes}[flush]\footnotesize
      \item At the milder $\cfh=5$ the fixed default still loses ($1.8\times$ baseline) while
            both principled policies stay at or below it; see \cref{sec:calibration}.
    \end{tablenotes}
  \end{threeparttable}
\end{table}
"""
    (TABLES / "calibration_table.tex").write_text(tex, encoding="utf-8")
    print("[table] calibration_table.tex (dcolumn, bold best)")


def main() -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    df = pd.read_csv(ROOT / "results" / "reliability_summary.csv")
    separability_table(df)
    fullresults_table(df)
    calibration_table()


if __name__ == "__main__":
    main()
