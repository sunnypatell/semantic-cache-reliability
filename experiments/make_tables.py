"""Generate the paper's LaTeX result tables from the experiment CSVs.

Numbers are pre-formatted to a fixed number of decimals here and emitted into plain
right/center-aligned booktabs columns, which aligns cleanly without siunitx. Writes
paper/tables/separability_table.tex and paper/tables/calibration_table.tex.

Run after run_reliability.py (and run_calibration.py for the calibration table):
    python experiments/make_tables.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "paper" / "tables"

ENC_ORDER = ["all-MiniLM-L6-v2", "all-mpnet-base-v2", "e5-small-v2", "e5-large-v2",
             "bge-base-en-v1.5", "bge-large-en-v1.5", "tfidf-lexical"]
ENC_LABEL = {"all-MiniLM-L6-v2": "MiniLM-L6", "all-mpnet-base-v2": "MPNet-base",
             "e5-small-v2": "E5-small", "e5-large-v2": "E5-large",
             "bge-base-en-v1.5": "BGE-base", "bge-large-en-v1.5": "BGE-large",
             "tfidf-lexical": "TF-IDF (lexical)"}
DOMAINS = ["qqp", "mrpc", "paws"]
DOMAIN_LABEL = {"qqp": "Questions", "mrpc": "News", "paws": "Adversarial"}


def _ci(v, lo, hi) -> str:
    return f"{v:.2f}\\,({lo:.2f},{hi:.2f})"


def separability_table() -> None:
    df = pd.read_csv(ROOT / "results" / "reliability_summary.csv")
    encs = [e for e in ENC_ORDER if e in set(df["encoder"])]
    rows = []
    for enc in encs:
        cells = [ENC_LABEL[enc]]
        for dom in DOMAINS:
            r = df[(df.encoder == enc) & (df.dataset == dom)]
            if len(r):
                r = r.iloc[0]
                cells.append(_ci(r.pr_auc, r.pr_auc_lo, r.pr_auc_hi))
            else:
                cells.append("--")
        rows.append(" & ".join(cells) + r" \\")
    body = "\n      ".join(rows)
    tex = r"""% Auto-generated by experiments/make_tables.py -- do not edit by hand.
\begin{table}[t]
  \centering
  \begin{threeparttable}
    \caption{Threshold-free separability (\prauc{}) with $95\%$ bootstrap intervals, for
      every encoder and domain. The adversarial column stays near its $0.44$ base rate for
      every encoder, including the largest; the lexical control is competitive there because
      neither lexical overlap nor learned semantics separates the classes.}
    \label{tab:separability}
    \begin{tabular}{l c c c}
      \toprule
      Encoder & Questions & News & Adversarial \\
      \midrule
      """ + body + r"""
      \bottomrule
    \end{tabular}
  \end{threeparttable}
\end{table}
"""
    (TABLES / "separability_table.tex").write_text(tex, encoding="utf-8")
    print("[table] separability_table.tex")


def calibration_table() -> None:
    path = ROOT / "results" / "calibration_summary.csv"
    if not path.exists():
        print("[table] calibration_summary.csv missing; leaving placeholder")
        return
    df = pd.read_csv(path)
    df = df[df.c_fh == 20.0]

    def kind(p: str) -> str:
        if p.startswith("fixed"):
            return "Fixed ($\\thr=0.80$)"
        if p.startswith("fhr"):
            return "Ceiling (FHR $\\leq 5\\%$)"
        return "Cost-aware (ours)"

    df = df.assign(kind=df.policy.map(kind))
    order = ["Fixed ($\\thr=0.80$)", "Ceiling (FHR $\\leq 5\\%$)", "Cost-aware (ours)"]
    rows = []
    for k in order:
        g = df[df.kind == k]
        rows.append(f"{k} & {100*g.fhr.mean():.1f} & {100*g.coverage.mean():.1f} "
                    f"& {g.expected_cost.mean():.3f} " + r"\\")
    body = "\n      ".join(rows)
    tex = r"""% Auto-generated by experiments/make_tables.py -- do not edit by hand.
\begin{table}[t]
  \centering
  \begin{threeparttable}
    \caption{Threshold policies on held-out test data, averaged over encoders and domains at
      a false-hit penalty of $c_{\mathrm{fh}}=20$. Expected cost is in model calls per query
      against the always-recompute baseline of $1$; lower is better.}
    \label{tab:calibration}
    \begin{tabular}{l r r r}
      \toprule
      Policy & FHR (\%) & Coverage (\%) & Expected cost \\
      \midrule
      """ + body + r"""
      \bottomrule
    \end{tabular}
  \end{threeparttable}
\end{table}
"""
    (TABLES / "calibration_table.tex").write_text(tex, encoding="utf-8")
    print("[table] calibration_table.tex")


def main() -> None:
    TABLES.mkdir(parents=True, exist_ok=True)
    separability_table()
    calibration_table()


if __name__ == "__main__":
    main()
